#!/usr/bin/env node
/**
 * Sync gait analytics config to JSON & Swift artifacts.
 * - Reads src/lib/gaitConfig.ts (static object literal)
 * - Writes src/fixtures/gait-config-export.json (pretty)
 * - Writes ios/HealthKitBridge/Generated/GaitConfig.swift (parity for iOS)
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

// Derive repository root; normalize Windows leading slash in file URL path
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
// We are at repoRoot/scripts/node/gait -> ascend three levels to repoRoot
const repoRoot = path.resolve(scriptDir, '../../..');
const tsFile = path.join(repoRoot, 'src', 'lib', 'gaitConfig.ts');
const jsonOut = path.join(repoRoot, 'src', 'fixtures', 'gait-config-export.json');
const swiftDir = path.join(repoRoot, 'ios', 'HealthKitBridge', 'Generated');
const swiftOut = path.join(swiftDir, 'GaitConfig.swift');

function extractObjectLiteral(ts) {
  const marker = 'export const gaitConfig =';
  const idx = ts.indexOf(marker);
  if (idx === -1) throw new Error('gaitConfig export not found');
  const braceStart = ts.indexOf('{', idx);
  if (braceStart === -1) throw new Error('Opening brace not found');
  let depth = 0;
  for (let i = braceStart; i < ts.length; i++) {
    const ch = ts[i];
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) {
        return ts.slice(braceStart, i + 1);
      }
    }
  }
  throw new Error('Failed to balance braces for gaitConfig');
}

function parseConfig(literal) {
  const code = 'config = ' + literal;
  const sandbox = {};
  vm.createContext(sandbox);
  vm.runInContext(code, sandbox, { timeout: 500 });
  return sandbox.config;
}

function deepStable(obj) {
  if (obj && typeof obj === 'object' && !Array.isArray(obj)) {
    return Object.keys(obj)
      .sort()
      .reduce((acc, k) => {
        acc[k] = deepStable(obj[k]);
        return acc;
      }, {});
  }
  if (Array.isArray(obj)) return obj.map(deepStable);
  return obj;
}

function computeHash(obj) {
  const json = JSON.stringify(obj);
  let h = 0x811c9dc5;
  for (let i = 0; i < json.length; i++) {
    h ^= json.charCodeAt(i);
    h = (h >>> 0) * 0x01000193;
  }
  return ('00000000' + (h >>> 0).toString(16)).slice(-8);
}

function writeJson(config) {
  // Preserve insertion order for hashing to align with runtime GAIT_ANALYTICS_VERSION
  const version = computeHash(config);
  const wrapped = { version, config };
  const current = fs.existsSync(jsonOut) ? fs.readFileSync(jsonOut, 'utf-8') : null;
  const next = JSON.stringify(wrapped, null, 2) + '\n';
  if (current !== next) {
    fs.writeFileSync(jsonOut, next, 'utf-8');
    console.log('Updated', path.relative(repoRoot, jsonOut));
  } else {
    console.log('JSON export up-to-date');
  }
}

function writeSwift(config) {
  fs.mkdirSync(swiftDir, { recursive: true });
  const version = computeHash(config);
  const swift = `// Auto-generated by gait:sync. Do NOT edit manually.\nimport Foundation\n\nstruct GaitConfig {\n    static let version: String = "${version}"\n    static let stabilityRelativeSlopeThreshold: Double = ${config.stabilityRelativeSlopeThreshold}\n    static let minimumConfidence: Double = ${config.minimumConfidence}\n\n    struct Magnitude {\n        static let strong: Double = ${config.magnitude.strong}\n        static let moderate: Double = ${config.magnitude.moderate}\n    }\n\n    struct Momentum {\n        static let relativeSlopeNormalizer: Double = ${config.momentum.relativeSlopeNormalizer}\n        static let fallbackRelative: Double = ${config.momentum.fallbackRelative}\n        static let upwardThreshold: Double = ${config.momentum.upwardThreshold}\n        static let downwardThreshold: Double = ${config.momentum.downwardThreshold}\n    }\n}\n`;
  const current = fs.existsSync(swiftOut) ? fs.readFileSync(swiftOut, 'utf-8') : null;
  if (current !== swift) {
    fs.writeFileSync(swiftOut, swift, 'utf-8');
    console.log('Updated', path.relative(repoRoot, swiftOut));
  } else {
    console.log('Swift export up-to-date');
  }
}

try {
  const ts = fs.readFileSync(tsFile, 'utf-8');
  const literal = extractObjectLiteral(ts);
  const cfg = parseConfig(literal);
  const required = ['stabilityRelativeSlopeThreshold', 'minimumConfidence', 'magnitude', 'momentum'];
  for (const k of required) if (!(k in cfg)) throw new Error('Missing key in parsed config: ' + k);
  writeJson(cfg);
  writeSwift(cfg);
  console.log('Gait config sync complete.');
} catch (e) {
  console.error('Failed to sync gait config:', e.message);
  process.exit(1);
}
