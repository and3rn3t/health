#!/usr/bin/env node
/**
 * generate-api-types.mjs
 *
 * Generates TypeScript types from the OpenAPI spec.
 *
 * The spec is extracted by running a Vitest helper that imports the Worker
 * (using existing Vite alias resolution) and writes the spec to a temp file.
 * Then openapi-typescript converts the JSON to TypeScript types.
 *
 * Usage:
 *   node scripts/ci/generate-api-types.mjs          # generate
 *   node scripts/ci/generate-api-types.mjs --check   # verify up-to-date
 */
import { writeFileSync, readFileSync, unlinkSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const outFile = resolve(repoRoot, 'src/lib/api-types.generated.ts');
const specFile = resolve(repoRoot, '.openapi-spec.tmp.json');
const isCheck = process.argv.includes('--check');

// ---------------------------------------------------------------------------
// 1. Extract spec by running the extract helper via vitest
// ---------------------------------------------------------------------------
console.log('📋 Extracting OpenAPI spec from Worker...');

try {
  execSync(
    `npx vitest run --reporter=verbose src/__tests__/extract-openapi-spec.test.ts 2>&1`,
    { encoding: 'utf-8', cwd: repoRoot, stdio: 'pipe' }
  );
} catch (err) {
  // Vitest may exit non-zero if the "test" fails; check if the file was written
  if (!existsSync(specFile)) {
    console.error('❌ Failed to extract spec:', err.stderr || err.message);
    process.exit(1);
  }
}

if (!existsSync(specFile)) {
  console.error('❌ Spec file not generated. Check extract-openapi-spec.test.ts');
  process.exit(1);
}

console.log('   Spec extracted successfully');

// ---------------------------------------------------------------------------
// 2. Generate types via openapi-typescript CLI
// ---------------------------------------------------------------------------
console.log('🔧 Generating TypeScript types...');
const header = '/* eslint-disable */\n/* This file is auto-generated by scripts/ci/generate-api-types.mjs — DO NOT EDIT */\n';

try {
  const bin = resolve(repoRoot, 'node_modules/.bin/openapi-typescript');
  const result = execSync(
    `"${bin}" "${specFile}" --export-type`,
    { encoding: 'utf-8', cwd: repoRoot }
  );

  const content = header + result;

  if (isCheck) {
    let existing = '';
    try {
      existing = readFileSync(outFile, 'utf-8');
    } catch {
      console.error(`❌ Generated types file does not exist: ${outFile}`);
      console.error('   Run: pnpm run generate:api-types');
      process.exit(1);
    }

    if (existing !== content) {
      console.error('❌ Generated API types are out of date!');
      console.error('   Run: pnpm run generate:api-types');
      process.exit(1);
    }

    console.log('✅ Generated API types are up to date');
  } else {
    writeFileSync(outFile, content);
    console.log(`✅ Types written to ${outFile}`);
  }
} finally {
  // Clean up temp spec file
  try {
    unlinkSync(specFile);
  } catch {
    // ignore
  }
}
