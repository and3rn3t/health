#!/usr/bin/env node
/**
 * Sync fall risk analytics config to JSON & (future) Swift artifacts.
 * Similar to gait:sync for parity and drift detection.
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '../../..');
const tsFile = path.join(repoRoot, 'src', 'lib', 'fallRiskConfig.ts');
const jsonOut = path.join(repoRoot, 'src', 'fixtures', 'fall-risk-config-export.json');
const swiftDir = path.join(repoRoot, 'ios', 'HealthKitBridge', 'Generated');
const swiftOut = path.join(swiftDir, 'FallRiskConfig.swift');

function extractObjectLiteral(ts) {
  const marker = 'export const fallRiskConfig =';
  const idx = ts.indexOf(marker);
  if (idx === -1) throw new Error('fallRiskConfig export not found');
  const braceStart = ts.indexOf('{', idx);
  if (braceStart === -1) throw new Error('Opening brace not found');
  let depth = 0;
  for (let i = braceStart; i < ts.length; i++) {
    const ch = ts[i];
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) return ts.slice(braceStart, i + 1);
    }
  }
  throw new Error('Failed to balance braces for fallRiskConfig');
}

function parseConfig(literal) {
  const code = 'config = ' + literal;
  const sandbox = {};
  vm.createContext(sandbox);
  vm.runInContext(code, sandbox, { timeout: 500 });
  return sandbox.config;
}

function deepStable(obj) {
  if (obj && typeof obj === 'object' && !Array.isArray(obj)) {
    return Object.keys(obj)
      .sort()
      .reduce((acc, k) => {
        acc[k] = deepStable(obj[k]);
        return acc;
      }, {});
  }
  if (Array.isArray(obj)) return obj.map(deepStable);
  return obj;
}

function computeHash(obj) {
  const json = JSON.stringify(obj);
  let h = 0x811c9dc5;
  for (let i = 0; i < json.length; i++) {
    h ^= json.charCodeAt(i);
    h = (h >>> 0) * 0x01000193;
  }
  return ('00000000' + (h >>> 0).toString(16)).slice(-8);
}

function writeJson(stable, version) {
  const wrapped = { version, config: stable };
  const current = fs.existsSync(jsonOut) ? fs.readFileSync(jsonOut, 'utf-8') : null;
  const next = JSON.stringify(wrapped, null, 2) + '\n';
  if (current !== next) {
    fs.writeFileSync(jsonOut, next, 'utf-8');
    console.log('Updated', path.relative(repoRoot, jsonOut));
  } else {
    console.log('JSON export up-to-date');
  }
}

function writeSwift(stable, version) {
  fs.mkdirSync(swiftDir, { recursive: true });
  const swift = `// Auto-generated by fall-risk:sync. Do NOT edit manually.\nimport Foundation\n\nstruct FallRiskConfig {\n    static let version: String = \"${version}\"\n    struct WalkingSteadiness {\n        static let criticalThreshold: Double = ${stable.walkingSteadiness.criticalThreshold}\n        static let highThreshold: Double = ${stable.walkingSteadiness.highThreshold}\n        static let moderateThreshold: Double = ${stable.walkingSteadiness.moderateThreshold}\n        struct Points {\n            static let critical: Int = ${stable.walkingSteadiness.points.critical}\n            static let high: Int = ${stable.walkingSteadiness.points.high}\n            static let moderate: Int = ${stable.walkingSteadiness.points.moderate}\n        }\n    }\n    struct RiskScoreClassification {\n        static let critical: Int = ${stable.riskScoreClassification.critical}\n        static let high: Int = ${stable.riskScoreClassification.high}\n        static let moderate: Int = ${stable.riskScoreClassification.moderate}\n    }\n    struct ModelScoreThresholds {\n        static let severe: Double = ${stable.modelScoreThresholds.severe}\n        static let high: Double = ${stable.modelScoreThresholds.high}\n        static let moderate: Double = ${stable.modelScoreThresholds.moderate}\n        static let confidenceAdjustmentFactor: Double = ${stable.modelScoreThresholds.confidenceAdjustmentFactor}\n    }\n    struct AggregationWeights {\n        static let fallEvent: Int = ${stable.aggregationWeights?.fallEvent ?? 0}\n        static let stateCritical: Int = ${stable.aggregationWeights?.state?.critical ?? 0}\n        static let stateHigh: Int = ${stable.aggregationWeights?.state?.high ?? 0}\n    }\n}\n`;
  const current = fs.existsSync(swiftOut) ? fs.readFileSync(swiftOut, 'utf-8') : null;
  if (current !== swift) {
    fs.writeFileSync(swiftOut, swift, 'utf-8');
    console.log('Updated', path.relative(repoRoot, swiftOut));
  } else {
    console.log('Swift export up-to-date');
  }
}

try {
  const ts = fs.readFileSync(tsFile, 'utf-8');
  const literal = extractObjectLiteral(ts);
  const cfg = parseConfig(literal);
  const required = ['walkingSteadiness', 'riskScoreClassification', 'modelScoreThresholds'];
  for (const k of required) if (!(k in cfg)) throw new Error('Missing key in parsed config: ' + k);
  // Preserve original property insertion order to match TS hash computation.
  const stable = cfg;
  const version = computeHash(stable);
  writeJson(stable, version);
  writeSwift(stable, version);
  console.log('Fall risk config sync complete.');
} catch (e) {
  console.error('Failed to sync fall risk config:', e.message);
  process.exit(1);
}
